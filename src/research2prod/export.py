"""The deployable unit. Everything an operator needs, nothing they must write.

``research2prod export`` takes the latest promoted version and lays out a directory
that runs on its own: the signal's source, the certificate, the frozen
project ground, a runner, a container, a schedule, and a README written for
the person who has to operate it rather than the person who wrote it.

There is no code generation of a "production version" here. The runner calls
the same function through the same view the research did. That is the entire
reason the export can be instant: nothing is being translated, so nothing can
be lost in translation.
"""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass
from pathlib import Path

from .config import Config
from .promote import DEFAULT_PROMOTED_DIR, history

RUNNER = '''"""Run {model} v{version} for one date and publish it. Generated by `research2prod export`.

    python run.py --as-of 2026-09-15          # price one day
    python run.py                             # today, in the calendar of research2prod.toml

Data is read from ./data/<input>.csv (mount or sync it there). Output goes to
the sink declared in research2prod.toml. Exit code is non-zero on any failure, so a
scheduler can alert on it.
"""
from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))  # the signal module lives next to this file

from research2prod import registry, run  # noqa: E402
from research2prod.config import load_config  # noqa: E402
from research2prod.sink import publish, rows_from_output  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--as-of", default=date.today().isoformat())
    parser.add_argument("--data", default=str(HERE / "data"))
    args = parser.parse_args()
    as_of = date.fromisoformat(args.as_of)

    config = load_config(HERE / "research2prod.toml")
    if as_of not in config.calendar.dates(as_of, as_of):
        print(f"{{as_of}} is not a pricing day in this calendar; nothing to do")
        return 0
    model = registry.load_file(HERE / "{source}")["{model}"]
    result = run(model, as_of, data_dir=args.data)
    rows = rows_from_output(result.output, as_of=as_of, model="{model}", version={version},
                            fingerprint="{fingerprint}")
    print(publish(rows, config.sink, root=HERE))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

DOCKERFILE = '''FROM python:{python}-slim
WORKDIR /job
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
# Data is mounted at /job/data by the scheduler; the sink is declared in research2prod.toml.
ENTRYPOINT ["python", "run.py"]
'''

WORKFLOW = '''name: {model} v{version}
on:
  schedule:
    - cron: "{schedule}"
  workflow_dispatch:
    inputs:
      as_of:
        description: "Date to price (YYYY-MM-DD); default today"
        required: false
jobs:
  price:
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: {bundle_dir}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "{python}"
      - run: pip install -r requirements.txt
      # Put your data sync here: the job expects ./data/<input>.csv for every
      # declared input. The contracts in research2prod.toml say what each file must hold.
      - run: python run.py ${{{{ inputs.as_of && format('--as-of {{0}}', inputs.as_of) || '' }}}}
        env:
          RESEARCH2PROD_SINK_TOKEN: ${{{{ secrets.RESEARCH2PROD_SINK_TOKEN }}}}
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: {model}-signals
          path: {bundle_dir}/signals/
'''

README = '''# {model} v{version} — deployable bundle

Generated by `research2prod export` from certificate `{fingerprint}` on {promoted_at}.
Nothing in this directory was hand-written after the research was done.

## What runs

`python run.py --as-of YYYY-MM-DD` prices one day: it loads `{source}`,
hands it a view of `./data/` bounded at that date, and publishes
`(as_of, key, score, model, version, fingerprint, published_at)` rows to the
sink in `research2prod.toml` (`{sink_kind}` → `{sink_target}`).

## What you have to provide

| | |
|---|---|
| **Data** | one CSV per declared input under `./data/`: {inputs}. Each must honour its contract (columns, types, knowledge-time column) in `research2prod.toml` — the same contracts the researcher was gated against. |
| **Schedule** | `.github/workflows/{model}.yml` runs it at `{schedule}` UTC; or build the `Dockerfile` and run it from any scheduler. |
| **Sink credentials** | for an `http` sink, set `RESEARCH2PROD_SINK_TOKEN`. |

## How to check it is right

`research2prod replay {model} --version {version}` re-runs the checked date and compares to the
golden output in the certificate. Same answer: the world has not moved. Different answer,
same source hash: the data was restated — talk to `{owner}`, the contract owner.

## Provenance

- declaration fingerprint `{fingerprint}` · source `{source}` sha256 `{source_sha}`
- ground `{project_fingerprint}` (calendar, universe, costs, splits, contracts)
- probes at promotion: {probes}
- backtest, validation split: {backtest}
- environment: Python {python}, {packages}

Research only. Nothing here is investment advice.
'''


@dataclass
class Bundle:
    model: str
    version: int
    path: Path


def export(
    name: str,
    *,
    config: Config,
    version: int | None = None,
    models_dir: Path | str = "examples",
    promoted_dir: Path | str = DEFAULT_PROMOTED_DIR,
    config_path: Path | str = "research2prod.toml",
) -> Bundle:
    versions = history(name, promoted_dir=promoted_dir)
    if not versions:
        raise KeyError(f"{name} has never been promoted; there is nothing to export")
    payload = versions[-1] if version is None else next((p for p in versions if p["version"] == version), None)
    if payload is None:
        raise KeyError(f"{name} v{version} was never promoted")

    source = payload["source"]["path"]
    if not source:
        raise ValueError("the certificate has no source path; promote again from a file on disk")
    source_path = Path(models_dir) / source
    if not source_path.is_file():
        raise FileNotFoundError(f"{source_path} not found; the bundle needs the promoted body")

    target = Path(promoted_dir) / name / f"v{payload['version']}"
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True)
    (target / "data").mkdir()
    (target / "signals").mkdir()
    (target / ".github" / "workflows").mkdir(parents=True)

    shutil.copy2(source_path, target / source)
    shutil.copy2(Path(config_path), target / "research2prod.toml")
    (target / "certificate.json").write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n", encoding="utf-8")

    env = payload["environment"]
    python = ".".join(env["python"].split(".")[:2])
    packages = env["packages"]
    requirements = "\n".join(
        f"{pkg}=={ver}" if ver else pkg for pkg, ver in packages.items()
    ) + "\n"
    (target / "requirements.txt").write_text(requirements, encoding="utf-8")

    fields = dict(
        model=name, version=payload["version"], fingerprint=payload["fingerprint"],
        source=source, python=python, schedule=config.schedule,
        bundle_dir=target.resolve().relative_to(Path(config_path).resolve().parent).as_posix()
        if target.resolve().is_relative_to(Path(config_path).resolve().parent) else target.as_posix(),
    )
    (target / "run.py").write_text(RUNNER.format(**fields), encoding="utf-8")
    (target / "Dockerfile").write_text(DOCKERFILE.format(**fields), encoding="utf-8")
    workflow = WORKFLOW.format(**fields)
    (target / ".github" / "workflows" / f"{name}.yml").write_text(workflow, encoding="utf-8")
    # GitHub only runs workflows from the repository root, so the schedule
    # lives there too, named for the signal. Re-exporting a newer version
    # replaces it: one signal, one job.
    project_root = Path(config_path).resolve().parent
    root_workflows = project_root / ".github" / "workflows"
    root_workflows.mkdir(parents=True, exist_ok=True)
    (root_workflows / f"research2prod-{name}.yml").write_text(workflow, encoding="utf-8")

    validation = ((payload.get("backtest") or {}).get("by_split") or {}).get("validation") or {}
    owner = next((c["owner"] for c in payload.get("contracts", [])), "the platform")
    (target / "README.md").write_text(README.format(
        **fields,
        promoted_at=payload["promoted_at"],
        sink_kind=config.sink.kind, sink_target=config.sink.target,
        inputs=", ".join(f"`{i['name']}.csv`" for i in payload["spec"]["inputs"]) or "none",
        owner=owner,
        source_sha=payload["source"]["sha256"],
        project_fingerprint=payload.get("project_fingerprint"),
        probes=", ".join(f"{p['probe']} {'pass' if p['passed'] else 'FAIL'}" for p in payload["probes"]),
        backtest=", ".join(f"{k} {v}" for k, v in validation.items()) or "not recorded",
        packages=", ".join(f"{k} {v}" for k, v in packages.items() if v),
    ), encoding="utf-8")
    return Bundle(name, payload["version"], target)
